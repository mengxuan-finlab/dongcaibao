function normalizeSymbol(symbol) {
  return String(symbol || '').trim().toUpperCase();
}

function detectMarket(symbol) {
  const value = normalizeSymbol(symbol);
  if (/^\d{4}(\.TW|\.TWO)?$/.test(value)) return 'TW';
  return 'US';
}

